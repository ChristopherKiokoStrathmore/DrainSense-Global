-- Target: NgaoDB (Oracle ADB, eu-frankfurt-1), schema WKSP_NGAO. Needs Oracle 23ai/26ai (CREATE TABLE IF NOT EXISTS).
-- Adds the climate dataset (Nino3.4 / ONI / DMI + CHIRPS ward rainfall) and the v3 seasonal-model outputs.
-- Touches NO existing object. All new objects are prefixed CLIMATE_ / SEASONAL_ / V_CLIMATE_ / V_SEASONAL_ ...
-- Data is loaded by load_climate_seasonal.py (INSERTs are not in this file). Re-running this file keeps data.
SET DEFINE OFF

-- 1. ENSO / IOD indices, one row per month (1870-2026; NULL where the index is not published)
CREATE TABLE IF NOT EXISTS climate_indices_monthly (
  year         NUMBER(4)   NOT NULL,
  month        NUMBER(2)   NOT NULL,
  period_date  DATE        NOT NULL,            -- first day of the month
  nino34       NUMBER(6,3),                     -- Nino3.4 SST anomaly degC (NOAA PSL, ERSST v6, base 1981-2010), 1948-
  oni          NUMBER(6,3),                     -- Oceanic Nino Index degC (NOAA CPC 3-month mean), centred on the middle month, 1950-
  dmi          NUMBER(6,3),                     -- Indian Ocean Dipole Mode Index degC (NOAA PSL / HadISST1.1, preliminary), 1870-
  source_note  VARCHAR2(400),
  CONSTRAINT pk_climate_indices PRIMARY KEY (year, month),
  CONSTRAINT ck_climate_idx_month CHECK (month BETWEEN 1 AND 12)
);

-- 2. CHIRPS v2.0 monthly rainfall per NgaoDB ward (join: wards.geoboundaries_shape_id -> geoBoundaries ADM3 shapeID)
CREATE TABLE IF NOT EXISTS climate_ward_rain_monthly (
  ward_id            NUMBER(10)  NOT NULL,       -- WARDS.WARD_ID (NgaoDB id, NOT the geoBoundaries id)
  year               NUMBER(4)   NOT NULL,
  month              NUMBER(2)   NOT NULL,
  period_date        DATE        NOT NULL,
  rainfall_mm        NUMBER(8,3),                -- mean of CHIRPS 0.05 deg pixels in the ward
  clim_1991_2020_mm  NUMBER(8,3),                -- 1991-2020 mean for that calendar month and ward
  rain_anomaly_mm    NUMBER(8,3),
  rain_anomaly_pct   NUMBER(9,3),                -- NULL where climatology = 0
  pixel_method       VARCHAR2(12),               -- centre | all_touched
  n_pixels           NUMBER(6),
  source_note        VARCHAR2(200),
  CONSTRAINT pk_climate_ward_rain PRIMARY KEY (ward_id, year, month),
  CONSTRAINT fk_climate_ward_rain_ward FOREIGN KEY (ward_id) REFERENCES wards (ward_id)
);
CREATE INDEX IF NOT EXISTS ix_climate_ward_rain_date ON climate_ward_rain_monthly (period_date);

-- 3. One row per evaluated model configuration (the v3 model card)
CREATE TABLE IF NOT EXISTS seasonal_model_runs (
  run_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  model_version       VARCHAR2(60)  NOT NULL,     -- e.g. v3-lit-logistic
  role                VARCHAR2(20)  NOT NULL,     -- RECOMMENDED | BASELINE | VARIANT
  target              VARCHAR2(10)  NOT NULL,     -- y25 = OND >+25% vs 1991-2020 ; yter = above upper tercile (KMD 'above normal')
  target_desc         VARCHAR2(200),
  season              VARCHAR2(10)  DEFAULT 'OND',
  issue_point         VARCHAR2(60),
  train_period        VARCHAR2(60),
  test_period         VARCHAR2(60),
  features            VARCHAR2(300),
  algorithm           VARCHAR2(80),
  n_test_ward_seasons NUMBER,
  n_effective_seasons NUMBER,
  accuracy            NUMBER(6,4),
  precision_score     NUMBER(6,4),
  recall_score        NUMBER(6,4),
  f1                  NUMBER(6,4),
  auc                 NUMBER(6,4),
  auc_ci90_lo         NUMBER(6,4),
  auc_ci90_hi         NUMBER(6,4),
  brier               NUMBER(6,4),
  decision_threshold  NUMBER(6,4),
  cv_auc              NUMBER(6,4),
  loyo_f1_min         NUMBER(6,4),
  loyo_f1_max         NUMBER(6,4),
  year_corr           NUMBER(6,4),
  caveats             CLOB,
  source_file         VARCHAR2(200),
  created_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
);

-- 4. Backtest per test year (observed vs predicted, across all 1,452 CHIRPS wards, not only NgaoDB's 61)
CREATE TABLE IF NOT EXISTS seasonal_backtest (
  run_id            NUMBER       NOT NULL,
  test_year         NUMBER(4)    NOT NULL,
  observed_wet_share NUMBER(6,4),                -- share of Kenyan wards whose OND met the target
  mean_pred_prob    NUMBER(6,4),                 -- mean predicted probability across those wards
  CONSTRAINT pk_seasonal_backtest PRIMARY KEY (run_id, test_year),
  CONSTRAINT fk_seasonal_backtest_run FOREIGN KEY (run_id) REFERENCES seasonal_model_runs (run_id)
);

-- 5. Live outlook, per ward and season. Written by the monthly job / backend only when a real forecast exists.
CREATE TABLE IF NOT EXISTS seasonal_outlook (
  outlook_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ward_id       NUMBER(10)   NOT NULL,
  season        VARCHAR2(20) NOT NULL,           -- e.g. 'OND 2026'
  probability   NUMBER(6,4)  NOT NULL,           -- P(target) for the season
  category      VARCHAR2(20),                    -- HIGH (p>=0.5) | MEDIUM (p>=model threshold) | LOW
  confidence    NUMBER(5,2),                     -- 0-100
  issued_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
  model_version VARCHAR2(60) NOT NULL,
  notes         VARCHAR2(400),
  CONSTRAINT fk_seasonal_outlook_ward FOREIGN KEY (ward_id) REFERENCES wards (ward_id),
  CONSTRAINT uq_seasonal_outlook UNIQUE (ward_id, season, model_version)
);

-- ===== Dashboard views =====
CREATE OR REPLACE VIEW v_climate_enso_latest AS
SELECT i.nino34_date, i.nino34, i.oni_date, i.oni, i.dmi_date, i.dmi,
       CASE WHEN i.oni >= 0.5 THEN 'EL NINO' WHEN i.oni <= -0.5 THEN 'LA NINA' ELSE 'NEUTRAL' END AS enso_phase,
       CASE WHEN i.dmi >= 0.4 THEN 'POSITIVE IOD' WHEN i.dmi <= -0.4 THEN 'NEGATIVE IOD' ELSE 'NEUTRAL' END AS iod_phase
FROM (
  SELECT (SELECT MAX(period_date) FROM climate_indices_monthly WHERE nino34 IS NOT NULL) AS nino34_date,
         (SELECT nino34 FROM climate_indices_monthly WHERE period_date=(SELECT MAX(period_date) FROM climate_indices_monthly WHERE nino34 IS NOT NULL)) AS nino34,
         (SELECT MAX(period_date) FROM climate_indices_monthly WHERE oni IS NOT NULL) AS oni_date,
         (SELECT oni FROM climate_indices_monthly WHERE period_date=(SELECT MAX(period_date) FROM climate_indices_monthly WHERE oni IS NOT NULL)) AS oni,
         (SELECT MAX(period_date) FROM climate_indices_monthly WHERE dmi IS NOT NULL) AS dmi_date,
         (SELECT dmi FROM climate_indices_monthly WHERE period_date=(SELECT MAX(period_date) FROM climate_indices_monthly WHERE dmi IS NOT NULL)) AS dmi
  FROM dual) i;

CREATE OR REPLACE VIEW v_seasonal_model_card AS
SELECT run_id, model_version, role, target, target_desc, season, issue_point, train_period, test_period,
       features, algorithm, n_test_ward_seasons, n_effective_seasons,
       accuracy, precision_score, recall_score, f1, auc, auc_ci90_lo, auc_ci90_hi, brier,
       decision_threshold, cv_auc, loyo_f1_min, loyo_f1_max, year_corr, caveats, source_file, created_at
FROM seasonal_model_runs;

CREATE OR REPLACE VIEW v_seasonal_backtest AS
SELECT b.run_id, r.model_version, r.role, r.target, b.test_year,
       b.observed_wet_share, b.mean_pred_prob,
       ROUND(b.mean_pred_prob - b.observed_wet_share, 4) AS error,
       ABS(ROUND(b.mean_pred_prob - b.observed_wet_share, 4)) AS abs_error,
       CASE WHEN ABS(b.mean_pred_prob - b.observed_wet_share) <= 0.15 THEN 'CLOSE'
            WHEN b.mean_pred_prob < b.observed_wet_share THEN 'UNDER-FORECAST'
            ELSE 'OVER-FORECAST' END AS calibration_flag   -- |predicted - observed| <= 0.15 counts as CLOSE
FROM seasonal_backtest b JOIN seasonal_model_runs r ON r.run_id = b.run_id;

CREATE OR REPLACE VIEW v_ward_rain_anomaly_latest AS
WITH last_m AS (SELECT MAX(period_date) AS d FROM climate_ward_rain_monthly)
SELECT w.ward_id, w.ward_name, w.county, c.period_date AS as_of_month,
       c.rainfall_mm, c.clim_1991_2020_mm, c.rain_anomaly_mm, c.rain_anomaly_pct,
       (SELECT ROUND(AVG(x.rain_anomaly_pct),1) FROM climate_ward_rain_monthly x
         WHERE x.ward_id = c.ward_id AND x.period_date > ADD_MONTHS(c.period_date,-3) AND x.period_date <= c.period_date) AS anomaly_pct_3m_avg,
       i.oni AS oni_same_month, i.nino34 AS nino34_same_month, i.dmi AS dmi_same_month
FROM climate_ward_rain_monthly c
JOIN last_m l ON l.d = c.period_date
JOIN wards w ON w.ward_id = c.ward_id
LEFT JOIN climate_indices_monthly i ON i.year = c.year AND i.month = c.month;

CREATE OR REPLACE VIEW v_seasonal_outlook_latest AS
SELECT o.outlook_id, o.ward_id, w.ward_name, w.county, o.season, o.probability, o.category, o.confidence, o.issued_at,
       o.model_version, r.role AS model_role, r.auc AS model_backtest_auc, o.notes
FROM seasonal_outlook o
JOIN wards w ON w.ward_id = o.ward_id
LEFT JOIN seasonal_model_runs r ON r.model_version = o.model_version AND r.target = 'y25'
WHERE o.issued_at = (SELECT MAX(x.issued_at) FROM seasonal_outlook x WHERE x.ward_id = o.ward_id AND x.season = o.season AND x.model_version = o.model_version);
