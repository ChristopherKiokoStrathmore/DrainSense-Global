-- TABLE COOPERATIVES (storage/tablespace clauses stripped for portability)
DECLARE n NUMBER;
BEGIN
  -- all_tables + CURRENT_SCHEMA: the deploy may log in as ADMIN and work in WKSP_NGAO.
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner=SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AND table_name='COOPERATIVES';
  IF n=0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE cooperatives (
      coop_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 13) NOT NULL,
      coop_name VARCHAR2(100) NOT NULL,
      ward_id NUMBER,
      county VARCHAR2(60),
      contact_phone VARCHAR2(16),
      members NUMBER,
      is_demo CHAR(1) DEFAULT 'Y',
      PRIMARY KEY (coop_id),
      FOREIGN KEY (ward_id) REFERENCES wards (ward_id)
    )~';
  END IF;
END;
/

-- VIEW V_WARD_RISK_LATEST
CREATE OR REPLACE VIEW "V_WARD_RISK_LATEST" ("WARD_ID", "WARD_NAME", "COUNTY", "HAZARD", "ALERT_TYPE", "ALERT_NAME", "SERVICE", "RISK_SCORE", "RISK_LEVEL", "DECISION", "CONFIDENCE", "ABSTAIN_REASON", "AS_OF", "CENTROID_LAT", "CENTROID_LON", "COLOUR") AS 
  SELECT w.ward_id, w.ward_name, w.county, t.hazard, r.alert_type, t.name AS alert_name, t.service,
       r.probability AS risk_score, r.risk_level, r.decision, r.confidence_pct AS confidence, r.abstain_reason,
       r.score_date AS as_of, w.centroid_lat, w.centroid_lon,
       CASE r.decision WHEN 'ACT' THEN '#D32F2F' WHEN 'WATCH' THEN '#F9A825' WHEN 'ABSTAIN' THEN '#9E9E9E' ELSE '#388E3C' END AS colour
FROM risk_scores r JOIN wards w ON w.ward_id=r.ward_id JOIN alert_types t ON t.alert_type=r.alert_type
WHERE r.is_replay='N' AND r.score_date=(SELECT MAX(score_date) FROM risk_scores x WHERE x.is_replay='N' AND x.ward_id=r.ward_id AND x.alert_type=r.alert_type);

-- VIEW V_ALERT_QUEUE
CREATE OR REPLACE VIEW "V_ALERT_QUEUE" ("ALERT_ID", "STATUS", "HAZARD", "SEVERITY", "ALERT_TYPE", "WARD_ID", "WARD_NAME", "COUNTY", "SUBSCRIBER_ID", "PHONE", "ROLE", "LANG", "BODY", "BODY_LEN", "RISK_SCORE", "CONFIDENCE", "AS_OF", "CREATED_AT", "APPROVED_BY", "APPROVED_AT", "SENT_AT", "MESSAGE_ID", "IS_REPLAY") AS 
  SELECT a.alert_id, a.status, a.hazard, a.severity, a.alert_type, w.ward_id, w.ward_name, w.county,
       s.subscriber_id, s.phone, s.role, a.lang, a.body, LENGTH(a.body) AS body_len,
       r.probability AS risk_score, r.confidence_pct AS confidence, r.score_date AS as_of,
       a.created_at, a.approved_by, a.approved_at, a.sent_at, a.message_id, w.is_replay
FROM alerts a JOIN wards w ON w.ward_id=a.ward_id JOIN subscribers s ON s.subscriber_id=a.subscriber_id
JOIN risk_scores r ON r.score_id=a.score_id;

-- VIEW V_GARISSA_REPLAY
CREATE OR REPLACE VIEW "V_GARISSA_REPLAY" ("WARD_ID", "WARD_NAME", "SCORE_DATE", "RVF_RISK", "RISK_LEVEL", "DECISION", "CONFIDENCE", "RAIN_30D_MM", "NDVI", "SOIL_MOIST_TOP", "TANA_DISCHARGE_M3S", "INDEX_CASE_DATE", "DAYS_BEFORE_INDEX_CASE", "EVENTS_THIS_WEEK") AS 
  SELECT r.ward_id, w.ward_name, r.score_date, r.probability AS rvf_risk, r.risk_level, r.decision, r.confidence_pct AS confidence,
       f.rain_30d_mm, f.ndvi, f.soil_moist_top,
       (SELECT MAX(river_discharge_m3s) FROM tana_discharge t WHERE t.point='Tana@Garissa' AND t.feature_date=r.score_date) AS tana_discharge_m3s,
       (SELECT MIN(event_date) FROM rvf_timeline WHERE event LIKE 'Symptom onset%') AS index_case_date,
       (SELECT MIN(event_date) FROM rvf_timeline WHERE event LIKE 'Symptom onset%') - r.score_date AS days_before_index_case,
       (SELECT LISTAGG(e.event,'; ') FROM rvf_timeline e WHERE e.event_date BETWEEN r.score_date AND r.score_date+6) AS events_this_week
FROM risk_scores r JOIN wards w ON w.ward_id=r.ward_id
LEFT JOIN ward_features_daily f ON f.ward_id=r.ward_id AND f.feature_date=r.score_date
WHERE r.is_replay='Y';

-- VIEW V_RAIN_SERIES
CREATE OR REPLACE VIEW "V_RAIN_SERIES" ("WARD_ID", "WARD_NAME", "COUNTY", "FEATURE_DATE", "RAIN_1D_MM", "RAIN_7D_MM", "RAIN_30D_MM", "RAIN_ANOM_30D", "ERA5_RAIN_MM", "SOIL_MOIST_TOP", "NDVI", "RH_MEAN_PCT", "T2M_MEAN_C", "RIVER_DISCHARGE_M3S", "KIND") AS 
  SELECT f.ward_id, w.ward_name, w.county, f.feature_date, f.rain_1d_mm, f.rain_7d_mm, f.rain_30d_mm, f.rain_anom_30d,
       f.era5_rain_mm, f.soil_moist_top, f.ndvi, f.rh_mean_pct, f.t2m_mean_c, f.river_discharge_m3s, 'OBSERVED' AS kind
FROM ward_features_daily f JOIN wards w ON w.ward_id=f.ward_id
UNION ALL
SELECT fc.ward_id, w.ward_name, w.county, fc.valid_date, fc.rain_mm, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, 'FORECAST_GFS'
FROM forecasts fc JOIN wards w ON w.ward_id=fc.ward_id WHERE fc.source='GFS' AND fc.issue_date=(SELECT MAX(issue_date) FROM forecasts);
